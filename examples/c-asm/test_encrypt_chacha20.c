// print functions for test output
static void print_char(char c) {
    volatile char *uart = (volatile char *)0x10000000;
    *uart = c;
}

static void print_string(const char *str) {
    while (*str) print_char(*str++);
}

// Print a byte as two hex characters
static void print_hex8(uint8_t val) {
    const char hex[] = "0123456789abcdef";
    print_char(hex[(val >> 4) & 0xF]);
    print_char(hex[val & 0xF]);
}

// Print postivi decimal integer
static void print_dec(int n) {
    if (n == 0) { print_char('0'); return; }
    char buf[10];
    int i = 0;
    while (n > 0) { buf[i++] = '0' + (n % 10); n /= 10; }
    while (i > 0) print_char(buf[--i]);
}

// Print a byte buffer as hex 16 bytes per line
static void print_buf_hex(const uint8_t *buf, uint32_t len) {
    for (uint32_t i = 0; i < len; i++) {
        print_hex8(buf[i]);
        print_char(' ');
        if ((i + 1) % 16 == 0) {
            // ASCII column: print the last 16 bytes as printable chars
            print_char(' ');
            for (uint32_t j = i - 15; j <= i; j++) {
                uint8_t c = buf[j];
                print_char((c >= 0x20 && c < 0x7f) ? (char)c : '.');
            }
            print_string("\n  ");
        }
    }
    // Last partial line
    uint32_t rem = len % 16;
    if (rem != 0) {
        // Pad hex columns so ASCII lines up
        for (uint32_t i = rem; i < 16; i++) print_string("   ");
        print_char(' ');
        for (uint32_t j = len - rem; j < len; j++) {
            uint8_t c = buf[j];
            print_char((c >= 0x20 && c < 0x7f) ? (char)c : '.');
        }
        print_char('\n');
    }
}

// Test result tracking

static int tests_run    = 0;
static int tests_passed = 0;

/*
 * Compare two byte buffers byte-by-byte
 * Every byte counts as one test case
 * Prints [PASS] with byte count on full match, or [FAIL] per wrong byte
 * 
 */
static void check_buf(const char    *label,
                      const uint8_t *got,
                      const uint8_t *expected,
                      uint32_t       len)
{
    int fails = 0;
    for (uint32_t i = 0; i < len; i++) {
        tests_run++;
        if (got[i] == expected[i]) {
            tests_passed++;
        } else {
            fails++;
            print_string("  [FAIL] ");
            print_string(label);
            print_string(" byte[");
            print_dec((int)i);
            print_string("]: got=0x");
            print_hex8(got[i]);
            print_string("  expected=0x");
            print_hex8(expected[i]);
            print_string("\n");
        }
    }
    if (fails == 0) {
        print_string("\033[1;32m  [PASS] ");  // bold green
        print_string(label);
        print_string(" (");
        print_dec((int)len);
        print_string(" bytes correct)\033[0m\n");
    } else {
        print_string("\033[1;31m  [FAIL] ");  // bold red
        print_string(label);
        print_string(": ");
        print_dec(fails);
        print_string("/");
        print_dec((int)len);
        print_string(" bytes wrong\033[0m\n");
    }
}

